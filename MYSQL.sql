# BUSINESS INSIGHT QUESTIONS

# Q 1. WHICH CATEGORY GENERATE HIGEST REVENUE.
select
category,
ROUND(SUM(purchase_amount),2) AS highest_revenue
from customer_behaviour_analysis
group by category
order by highest_revenue desc;

-- BUSINESS PROBLEMS :- COMPANT DOES NOT KNOW WHICH CATEGORY CONTRIBUTE MOST TO REVENUE.
-- IMPACT :-- 
          # HELPS PRIORITIZE HIGH-PORFORMANCE CATEGORIES
          # OPTIMIZE INVENTORY PLANNING
          # IMPROVES MARKETING RIO

# Q 2. ARE DISCOUNT ACTUALLY INCREASING PURCHASE VALUE
SELECT 
      discount_applied,
      round(sum(purchase_amount),2) as total_revenue,
      round(avg(purchase_amount),2) as total_revenue
      from customer_behaviour_analysis
      group by discount_applied;
           
# BUSINES PROBLEM :-  Discount may reduce profit without increseing sales.

# IMPACT :-
         # IDENTIFY EFFECTIVENESS OF DISCOUNTS
         # REDUCE UNNECESSARY DISCOUNT COST.
         # Improve profit margines

# Q 3. WHAT IS THE REVANUE GENERATED BY MALE AND FEMAIL CUSTOMER

select
gender,
ROUND(SUM(purchase_amount),2) AS highest_revenue
from customer_behaviour_analysis
group by gender
order by highest_revenue desc;

# Q 4. WHICH CUSTOMER USED A DISCOUNT BUT STILL SPENT MORE THAN THE AVERAGE PURCHAGE AMOUNT.
SELECT 
    customer_id,
    purchase_amount,
    discount_applied
FROM customer_behaviour_analysis
where discount_applied="Yes" AND purchase_amount > (SELECT AVG(purchase_amount) from customer_behaviour_analysis);    
    
# Q 5. WHICH ARE THE TOP/BUTTOM 5 PRODUCTS WITH THE HIGEST AVERAGE REVIEW RATING.

